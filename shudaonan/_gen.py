# —— 合并 segs 成竖排列（长句成列，避免十几列铺满画面；文本必须与 queue 严格一致）——
for p in P:
    gs = groups[p['name']]
    merged = []
    for g in gs:
        c = ''.join(p['segs'][i][0] for i in g)
        py = ' '.join(p['segs'][i][1] for i in g)
        merged.append((c, py))
    assert ''.join(x[0] for x in merged) == ''.join(x[0] for x in p['segs']), '合并改变了文本: ' + p['name']
    p['segs'] = merged

bad = 0
joined = ''
PUNCT = '，。、！？；：…—·'
for i, p in enumerate(P):
    s = ''
    for c, py in p['segs']:
        han = [ch for ch in c if ch not in PUNCT]
        n = len(py.split(' '))
        if len(han) != n:
            print('!! jing%d seg [%s] han=%d py=%d : %s' % (i + 1, c, len(han), n, py)); bad += 1
        s += c
    joined += s
    if s != E['stages'][i]:
        print('!! jing%d text mismatch\n  want: %s\n  got : %s' % (i + 1, E['stages'][i], s)); bad += 1
    if not (2 <= len(p['zhu']) <= 4):
        print('!! jing%d zhu=%d' % (i + 1, len(p['zhu']))); bad += 1
if joined != E['text']:
    print('!! full text mismatch'); bad += 1
print('stages=%d problems=%d' % (len(P), bad))


def q(s):
    return s.replace(chr(92), chr(92) * 2).replace("'", chr(92) + "'")


out = []
for p in P:
    segs = ',\n        '.join("{c:'%s', p:py('%s')}" % (q(c), py) for c, py in p['segs'])
    zhu = ',\n      '.join("['%s','%s']" % (q(a), q(b)) for a, b in p['zhu'])
    out.append("{ name:'%s', jing:'%s',\n  segs:[%s],\n  read:'%s',\n  yisi:'%s',\n  zhu:[%s] }"
               % (p['name'], q(p['jing']), segs, q(p['read']), q(p['yisi']), zhu))
io.open('_poem.js', 'w', encoding='utf-8').write(',\n'.join(out))
