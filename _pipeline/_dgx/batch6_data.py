import re

BATCH6 = []


def _sentences(text):
    return re.findall(r'[^。？！]*[。？！]', text)


def mk(no, slug, title, author, dynasty, track, accent, text, split, moment, interact, note=''):
    ss = _sentences(text)
    assert ''.join(ss) == text, '分句丢失标点: %s' % slug
    assert sum(split) == len(ss), '%s: split 合计 %d ≠ 句数 %d' % (slug, sum(split), len(ss))
    stages, i = [], 0
    for n in split:
        stages.append(''.join(ss[i:i + n]))
        i += n
    BATCH6.append({'no': no, 'slug': slug, 'title': title, 'author': author, 'dynasty': dynasty,
                   'track': track, 'accent': accent, 'text': text, 'stages': stages,
                   'moment': moment, 'interact': interact, 'note': note})


